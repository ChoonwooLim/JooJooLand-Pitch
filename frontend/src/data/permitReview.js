// ── 추적 대상(trackable) 항목 평탄화 ────────────────────────
// 진행률 = 해결된 trackable / 전체 trackable
export function collectTrackables() {
  const list = [];
  criticalIssues.forEach((c) => list.push({ id: c.id, group: 'blocker', label: c.title }));
  categories.forEach((cat) => {
    cat.items.forEach((it) => {
      if (needsAction(it.result)) {
        list.push({ id: it.id, group: cat.id, label: `${cat.title} · ${it.name}` });
      }
    });
  });
  actionSteps.forEach((s) => list.push({ id: s.id, group: 'step', label: s.title }));
  return list;
}

export const TRACKABLE_IDS = collectTrackables().map((t) => t.id);
